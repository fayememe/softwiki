def wiki_titles(kb: str):
    seen = set()
    for title in WIKI.get(kb, []):
        key = title.strip().lower()
        if key in seen:
            continue
        seen.add(key)
        yield title


def urls(kb: str):
    seen = set()
    for url in URLS.get(kb, []):
        if url not in seen:
            seen.add(url)
            yield url


def feeds(kb: str):
    return RSS.get(kb, [])
